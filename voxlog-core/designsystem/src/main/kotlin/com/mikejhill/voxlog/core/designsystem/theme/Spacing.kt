package com.mikejhill.voxlog.core.designsystem.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** The 4 dp spacing scale used across every screen. */
object Spacing {
    /** 4 dp. */
    val extraSmall: Dp = 4.dp

    /** 8 dp. */
    val small: Dp = 8.dp

    /** 12 dp. */
    val medium: Dp = 12.dp

    /** 16 dp: default screen gutter. */
    val large: Dp = 16.dp

    /** 24 dp. */
    val extraLarge: Dp = 24.dp

    /** 32 dp. */
    val huge: Dp = 32.dp

    /** Minimum touch target per Material accessibility guidance. */
    val minimumTouchTarget: Dp = 48.dp
}
